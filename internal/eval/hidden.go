package eval

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Held-out acceptance tests are the instrument this package grew for a
// simple reason: a gate the model can run for itself never fails. A
// model that can read the grading tests runs them before it ends a turn,
// so the verification gate only ever confirms — 16 gate commands and 0
// failures on the hard set. Everything that triggers on a gate failure
// (triage, cascade escalation, repair rounds) is unmeasurable against
// such a gate.
//
// A task's Hidden files are therefore never written into the work
// directory. They live in a directory of their own outside the
// workspace, together with a generated script; the script copies the
// workspace into a fresh scratch directory, lays the held-out tests over
// the copy, runs one command there and deletes the copy. The agent's
// verification gate runs that script under a display label, so neither
// the tests, their directory nor the script's path ever reach the model
// — what reaches it is the command's output, which for `go test` is the
// failing test names and the assertion messages a real CI failure shows.

// HiddenDir is where a task's held-out tests are laid over the scratch
// copy. It is a package of its own so the held-out command can run that
// package alone: the model's own tests never execute in the scratch
// copy, which is what keeps a file the model wrote out of the run that
// can see the held-out sources.
const HiddenDir = "acceptance"

// defaultHiddenCheck runs the held-out package and nothing else.
const defaultHiddenCheck = "go test ./" + HiddenDir + "/"

// gateScript is the generated held-out gate. It takes the workspace as
// its first argument, works on a copy, and rewrites both its own
// directory and the scratch directory out of the output so a failure
// says what a CI failure says and no more.
const gateScript = `#!/bin/sh
# Held-out acceptance gate, generated by janetcode's eval runner.
set -u
W="${1:-}"
if [ -z "$W" ] || [ ! -d "$W" ]; then
	echo "held-out gate: no workspace given" >&2
	exit 2
fi
H=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd) || exit 2
S=$(mktemp -d "${TMPDIR:-/tmp}/jc-acceptance-XXXXXXXX") || exit 2
trap 'rm -rf "$S"' EXIT INT TERM
(cd "$W" && tar cf - .) | (cd "$S" && tar xf -) || exit 2
# Anything the run put where the held-out tests go is discarded before
# they are laid down: the overlay is the only thing in that package.
rm -rf "$S/%[1]s"
(cd "$H/tests" && tar cf - .) | (cd "$S" && tar xf -) || exit 2
cd "$S" || exit 2
out=$( { %[2]s ; } 2>&1 )
rc=$?
printf '%%s\n' "$out" | sed -e "s|$S/||g" -e "s|$S|.|g" -e "s|$H|<held-out>|g"
exit $rc
`

// Hidden reports whether the task ships held-out acceptance tests.
func (t Task) Hidden() bool { return len(t.HiddenFiles) > 0 }

// hiddenCheck is the command the held-out gate runs in the scratch copy.
func (t Task) hiddenCheck() string {
	if s := strings.TrimSpace(t.HiddenCheck); s != "" {
		return s
	}
	return defaultHiddenCheck
}

// prepareHidden materialises a task's held-out tests outside the work
// directory and returns the gate script's path. An empty path (and a
// no-op cleanup) means the task has none.
func prepareHidden(t Task) (gate string, cleanup func(), err error) {
	if !t.Hidden() {
		return "", func() {}, nil
	}
	dir, err := os.MkdirTemp("", "janetcode-heldout-")
	if err != nil {
		return "", func() {}, err
	}
	cleanup = func() { os.RemoveAll(dir) }
	tests := map[string]string{}
	for name, body := range t.HiddenFiles {
		tests[filepath.Join(HiddenDir, name)] = body
	}
	if err := writeFiles(filepath.Join(dir, "tests"), tests); err != nil {
		cleanup()
		return "", func() {}, err
	}
	gate = filepath.Join(dir, "gate.sh")
	body := fmt.Sprintf(gateScript, HiddenDir, t.hiddenCheck())
	if err := os.WriteFile(gate, []byte(body), 0o700); err != nil {
		cleanup()
		return "", func() {}, err
	}
	return gate, cleanup, nil
}

// HiddenGateLabel is how the held-out gate is named everywhere it is
// reported. The name has to say what failed without saying where it
// lives; see verify.Runner.Display.
const HiddenGateLabel = "acceptance tests"

// checkHiddenTask validates a task's held-out tests at load time. A
// held-out file that is also a visible file would defeat the whole
// instrument, and a held-out file outside the held-out package would be
// laid over the model's own work.
func checkHiddenTask(t Task) error {
	names := make([]string, 0, len(t.HiddenFiles))
	for name := range t.HiddenFiles {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		clean := filepath.Clean(name)
		if filepath.IsAbs(clean) || strings.HasPrefix(clean, "..") || strings.ContainsRune(clean, filepath.Separator) {
			return fmt.Errorf("hidden file %q must be a plain file name in the %s package", name, HiddenDir)
		}
		if _, ok := t.Files[filepath.Join(HiddenDir, clean)]; ok {
			return fmt.Errorf("hidden file %q is also a visible file", name)
		}
	}
	if strings.TrimSpace(t.HiddenCheck) != "" && !t.Hidden() {
		return fmt.Errorf("hidden_check is set but the task has no hidden files")
	}
	for name := range t.Files {
		if strings.HasPrefix(filepath.ToSlash(filepath.Clean(name)), HiddenDir+"/") && t.Hidden() {
			return fmt.Errorf("visible file %q is inside the held-out package %s", name, HiddenDir)
		}
	}
	return nil
}

// HiddenGateCommand is the shell command that runs the held-out gate
// script over the work directory. Both paths come from os.MkdirTemp, but
// they are single-quoted anyway: this string is handed to /bin/sh, and a
// path is never trusted to be free of shell metacharacters.
func HiddenGateCommand(gate, root string) string {
	return shQuote(gate) + " " + shQuote(root)
}

func shQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
